import { readFileSync, writeFileSync } from "node:fs";

const REQUIRED = [
  "bg",
  "surface",
  "surface-raised",
  "border",
  "border-strong",
  "text",
  "text-muted",
  "accent",
  "accent-text",
  "pass",
  "pass-bg",
  "fail",
  "fail-bg",
  "inconclusive",
  "inconclusive-bg",
  "info",
  "info-bg",
  "sidebar",
  "sidebar-text",
  "sidebar-muted",
  "sidebar-active",
  "sidebar-strong",
];

const source = readFileSync(new URL("../src/theme.generated.css", import.meta.url), "utf8");
const found: Record<"light" | "dark", Set<string>> = { light: new Set(), dark: new Set() };
const pattern = /--color-(light|dark)-([a-z0-9-]+)\s*:/g;
for (const match of source.matchAll(pattern)) {
  const theme = match[1];
  const name = match[2];
  if (theme === "light" || theme === "dark") {
    found[theme].add(name);
  }
}

const expected = new Set(REQUIRED);
function diff(actual: Set<string>): string[] {
  const missing = REQUIRED.filter((name) => !actual.has(name));
  const extra = [...actual].filter((name) => !expected.has(name)).sort();
  return [
    ...missing.map((name) => `missing ${name}`),
    ...extra.map((name) => `unexpected ${name}`),
  ];
}

const lightDiff = diff(found.light);
const darkDiff = diff(found.dark);
if (lightDiff.length > 0 || darkDiff.length > 0) {
  console.error("theme token sets do not match the semantic names");
  if (lightDiff.length > 0) {
    console.error(`light: ${lightDiff.join(", ")}`);
  }
  if (darkDiff.length > 0) {
    console.error(`dark: ${darkDiff.join(", ")}`);
  }
  process.exit(1);
}

function block(theme: "light" | "dark"): string {
  const declarations = REQUIRED.map(
    (name) => `  --${name}: var(--color-${theme}-${name});`,
  ).join("\n");
  return `[data-theme="${theme}"] {\n${declarations}\n  color-scheme: ${theme};\n}`;
}

const css = `/* generated by scripts/themes.ts from DESIGN.md; do not edit */\n${block("light")}\n${block("dark")}\n`;
writeFileSync(new URL("../src/themes.generated.css", import.meta.url), css);
